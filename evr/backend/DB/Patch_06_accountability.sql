ALTER TABLE users ADD COLUMN IF NOT EXISTS role varchar NOT NULL DEFAULT 'Staff';

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_users_role') THEN
        ALTER TABLE users ADD CONSTRAINT chk_users_role CHECK (role IN ('Owner', 'Staff'));
    END IF;
END $$;

UPDATE users
SET role = 'Owner'
WHERE id = (SELECT MIN(u.id) FROM users u WHERE u.status <> 'Deactivate')
  AND NOT EXISTS (SELECT 1 FROM users o WHERE o.role = 'Owner');

ALTER TABLE sessions ADD COLUMN IF NOT EXISTS started_by bigint REFERENCES users (id);
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS ended_by bigint REFERENCES users (id);
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS returned_by bigint REFERENCES users (id);
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS canceled_by bigint REFERENCES users (id);

CREATE INDEX IF NOT EXISTS ix_sessions_started_by ON sessions (started_by);
CREATE INDEX IF NOT EXISTS ix_sessions_scheduled_date ON sessions (scheduled_date);
CREATE INDEX IF NOT EXISTS ix_payments_session_id ON payments (session_id);
CREATE INDEX IF NOT EXISTS ix_tickets_session_id ON tickets (session_id);

UPDATE sessions s
SET started_by = COALESCE(
    (SELECT a.user_id FROM audit_logs a
     WHERE a.entity_type = 'session' AND a.action = 'session.start' AND a.entity_id = s.id
     ORDER BY a.id DESC LIMIT 1),
    s.created_by)
WHERE s.started_at IS NOT NULL AND s.started_by IS NULL;

UPDATE sessions s
SET ended_by = COALESCE(
    (SELECT a.user_id FROM audit_logs a
     WHERE a.entity_type = 'session' AND a.action = 'session.end' AND a.entity_id = s.id
     ORDER BY a.id DESC LIMIT 1),
    s.started_by,
    s.created_by)
WHERE s.status = 'Ended' AND s.ended_by IS NULL;

UPDATE tickets t
SET returned_by = COALESCE(
    (SELECT a.user_id FROM audit_logs a
     WHERE a.entity_type = 'ticket' AND a.action = 'ticket.return' AND a.entity_id = t.id
     ORDER BY a.id DESC LIMIT 1),
    t.created_by)
WHERE t.status = 'Completed' AND t.returned_by IS NULL;

UPDATE tickets t
SET canceled_by = COALESCE(
    (SELECT a.user_id FROM audit_logs a
     WHERE a.entity_type = 'ticket' AND a.action = 'ticket.cancel' AND a.entity_id = t.id
     ORDER BY a.id DESC LIMIT 1),
    t.created_by)
WHERE t.status = 'Canceled' AND t.canceled_by IS NULL;

CREATE TABLE IF NOT EXISTS vehicle_incidents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id bigint NOT NULL REFERENCES vehicles (id),
    session_id bigint REFERENCES sessions (id),
    ticket_id bigint REFERENCES tickets (id),
    source varchar NOT NULL CHECK (source IN ('Ticket', 'Manual')),
    reported_by bigint NOT NULL REFERENCES users (id),
    created_at timestamp NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_vehicle_incidents_created_at ON vehicle_incidents (created_at);
CREATE INDEX IF NOT EXISTS ix_vehicle_incidents_session_id ON vehicle_incidents (session_id);
CREATE INDEX IF NOT EXISTS ix_vehicle_incidents_vehicle_id ON vehicle_incidents (vehicle_id);

INSERT INTO vehicle_incidents (vehicle_id, session_id, ticket_id, source, reported_by, created_at)
SELECT h.vehicle_id,
       t.session_id,
       h.ticket_id,
       'Ticket',
       COALESCE(
           (SELECT a.user_id FROM audit_logs a
            WHERE a.entity_type = 'ticket' AND a.action = 'ticket.change_vehicle' AND a.entity_id = h.ticket_id
              AND a.created_at BETWEEN h.released_at - interval '1 minute' AND h.released_at + interval '1 minute'
            ORDER BY a.id DESC LIMIT 1),
           t.created_by),
       h.released_at
FROM ticket_vehicle_history h
JOIN tickets t ON t.id = h.ticket_id
WHERE h.released_status = 'Repairing'
  AND h.released_at IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM vehicle_incidents);
