CREATE TYPE "user_status" AS ENUM (
  'Online',
  'Offline',
  'Deactivate'
);

CREATE TYPE "vehicle_status" AS ENUM (
  'Online',
  'Repairing',
  'Offline',
  'Inused',
  'Deleted'
);

CREATE TYPE "session_status" AS ENUM (
  'Waiting',
  'InProgress',
  'Ended',
  'Canceled'
);

CREATE TYPE "ticket_status" AS ENUM (
  'Waiting',
  'Inused',
  'Overdue',
  'Canceled',
  'Completed'
);

CREATE TYPE "payment_method" AS ENUM (
  'Cash',
  'Bank'
);

CREATE TYPE "payment_type" AS ENUM (
  'Ticket',
  'Extension',
  'OverdueFee',
  'Refund'
);

CREATE TYPE "released_vehicle_status" AS ENUM (
  'Online',
  'Repairing'
);

CREATE TABLE "users" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "username" varchar UNIQUE NOT NULL,
  "password_hash" varchar NOT NULL,
  "status" user_status NOT NULL DEFAULT 'Offline',
  "cookie_hash" varchar,
  "cookie_expires_at" timestamp,
  "last_login_at" timestamp,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "vehicles" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "slug" varchar NOT NULL,
  "status" vehicle_status NOT NULL DEFAULT 'Offline',
  "deleted_at" timestamp,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "sessions" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "status" session_status NOT NULL DEFAULT 'Waiting',
  "scheduled_date" date NOT NULL,
  "scheduled_time" time NOT NULL,
  "planned_end_at" timestamp,
  "started_at" timestamp,
  "ended_at" timestamp,
  "is_instant" boolean NOT NULL DEFAULT false,
  "next_ticket_no" int NOT NULL DEFAULT 1,
  "created_by" bigint NOT NULL,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "session_vehicles" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "session_id" bigint NOT NULL,
  "vehicle_id" bigint NOT NULL,
  "added_at" timestamp NOT NULL DEFAULT (now()),
  "removed_at" timestamp,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "tickets" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "session_id" bigint NOT NULL,
  "ticket_no" int NOT NULL,
  "phone" varchar NOT NULL,
  "status" ticket_status NOT NULL DEFAULT 'Waiting',
  "vehicle_id" bigint,
  "payment_method" payment_method NOT NULL,
  "total_minutes" int NOT NULL,
  "amount_paid" int NOT NULL,
  "price_amount" int NOT NULL,
  "price_minutes" int NOT NULL,
  "overdue_fee_per_minute" int NOT NULL,
  "overdue_grace_minutes" int NOT NULL,
  "refund_enabled" boolean NOT NULL,
  "queued_at" timestamp NOT NULL,
  "started_at" timestamp,
  "due_at" timestamp,
  "returned_at" timestamp,
  "overdue_minutes" int NOT NULL DEFAULT 0,
  "overdue_fee" int NOT NULL DEFAULT 0,
  "refund_amount" int NOT NULL DEFAULT 0,
  "canceled_at" timestamp,
  "created_by" bigint NOT NULL,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "payments" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "session_id" bigint NOT NULL,
  "ticket_id" bigint NOT NULL,
  "type" payment_type NOT NULL,
  "method" payment_method NOT NULL,
  "amount" int NOT NULL,
  "minutes" int,
  "created_by" bigint NOT NULL,
  "created_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "ticket_vehicle_history" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ticket_id" bigint NOT NULL,
  "vehicle_id" bigint NOT NULL,
  "assigned_at" timestamp NOT NULL,
  "released_at" timestamp,
  "released_status" released_vehicle_status,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "settings" (
  "id" smallint PRIMARY KEY,
  "refund_enabled" boolean NOT NULL DEFAULT false,
  "extend_enabled" boolean NOT NULL DEFAULT true,
  "overdue_fee_per_minute" int NOT NULL DEFAULT 0,
  "overdue_grace_minutes" int NOT NULL DEFAULT 0,
  "minimum_minutes" int NOT NULL DEFAULT 0,
  "updated_by" bigint,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "price_packages" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "amount" int NOT NULL,
  "minutes" int NOT NULL,
  "is_default" boolean NOT NULL DEFAULT false,
  "active" boolean NOT NULL DEFAULT true,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "updated_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "audit_logs" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" bigint NOT NULL,
  "action" varchar NOT NULL,
  "entity_type" varchar NOT NULL,
  "entity_id" bigint,
  "payload" json,
  "created_at" timestamp NOT NULL DEFAULT (now())
);

